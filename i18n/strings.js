/** Dotted-key lookup with {var} fill. Falls back to Thai, then to the key. */
export function t(lang, key, vars) {
  const pick = (l) => key.split(".").reduce((o, k) => (o == null ? o : o[k]), STRINGS[l]);
  let v = pick(normLang(lang));
  if (v == null) v = pick(DEFAULT_LANG);
  if (v == null) return key;
  if (typeof v === "string" && vars) v = v.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return v;
}

/** Map an internal error code (order/payment/route) to its strings key, e.g. "errors.order_bad". */
export function errorKey(code) {
  const c = String(code || "");
  const k =
    /^order_bad/.test(c) ? "order_bad" :
    /^paid_bad/.test(c) ? "paid_bad" :
    /^config/.test(c) ? "config" :
    c;
  return k && STRINGS.th.errors[k] != null ? "errors." + k : "errors.read_failed";
}

/** Localized message for an internal error code. */
export function errorText(lang, code) {
  return t(lang, errorKey(code));
}
