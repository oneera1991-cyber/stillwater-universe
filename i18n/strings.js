/** "en", "EN", "en-US", "en_GB" → "en"; anything else (incl. missing) → "th".
    Same rule as Stillwater's normalizeLang() in api/_lib/vera.js. */
export function normLang(value) {
  const s = typeof value === "string" ? value.trim().toLowerCase() : "";
  return /^en([-_].*)?$/.test(s) ? "en" : "th";
}

