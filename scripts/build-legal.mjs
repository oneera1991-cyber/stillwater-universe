#!/usr/bin/env node
/*
Builds legal/content.js from Stillwater's final copy (legal/*.md, copied verbatim
from /workspace/stillwater/prompts/{terms,privacy}.{th,en}.md). Wording is NOT edited:
the converter only maps markdown structure (#, ##, "- " lists, **bold**,
paragraphs) to HTML, escapes everything else, and turns the support email into a
mailto: link and 1323 / 1669 into tel: links.

  node scripts/build-legal.mjs          # rewrite legal/content.js
  node scripts/build-legal.mjs --check  # exit 1 if legal/content.js is out of date (used by dev/unit.mjs)
*/
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function inline(text) {
  let h = esc(text).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
  h = h.replace(/([A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,})/g, '<a href="mailto:$1">$1</a>');
  h = h.replace(/(^|[^\d])(1323|1669)(?!\d)/g, '$1<a href="tel:$2">$2</a>');
  return h;
}

export function mdToHtml(md) {
  const out = [];
  let para = [], list = null;
  const flushPara = () => { if (para.length) { out.push(`<p>${inline(para.join(" "))}</p>`); para = []; } };
  const flushList = () => { if (list) { out.push(`<ul>${list.map((li) => `<li>${inline(li)}</li>`).join("")}</ul>`); list = null; } };
  for (const raw of md.replace(/\r\n?/g, "\n").split("\n")) {
    const line = raw.trimEnd();
    let m;
    if (!line.trim()) { flushPara(); flushList(); continue; }
    if ((m = line.match(/^(#{1,3}) (.+)$/))) {
      flushPara(); flushList();
      const n = m[1].length;
      out.push(`<h${n}>${inline(m[2])}</h${n}>`);
    } else if ((m = line.match(/^- (.+)$/))) {
      flushPara(); (list ||= []).push(m[1]);
    } else {
      flushList(); para.push(line.trim());
    }
  }
  flushPara(); flushList();
  return out.join("\n");
}

export function buildContent() {
  const doc = {};
  for (const page of ["terms", "privacy"]) {
    doc[page] = {};
    for (const lang of ["th", "en"]) doc[page][lang] = mdToHtml(readFileSync(path.join(ROOT, "legal", `${page}.${lang}.md`), "utf8"));
  }
  return `// GENERATED by scripts/build-legal.mjs from legal/*.md (Stillwater's final copy). Do not edit by hand.\n` +
    `export const LEGAL = ${JSON.stringify(doc, null, 2)};\n`;
}

const isMain = import.meta.url === `file://${process.argv[1]}`;
if (isMain) {
  const file = path.join(ROOT, "legal", "content.js");
  const next = buildContent();
  if (process.argv.includes("--check")) {
    let cur = ""; try { cur = readFileSync(file, "utf8"); } catch {}
    if (cur !== next) { console.error("legal/content.js is out of date — run node scripts/build-legal.mjs"); process.exit(1); }
    console.log("legal/content.js up to date");
  } else {
    writeFileSync(file, next);
    console.log("wrote", path.relative(ROOT, file));
  }
}
